import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, expect, it } from "vitest";
import { SERVICE_VERSION, type PrSummary } from "@gander/shared";
import { openStorage } from "../../../service/src/storage.js";
import { buildServer } from "../../../service/src/server.js";
import { makeFixtureRepo } from "./fixtures.js";
import { createGitEngine } from "./git.js";
import { createServerRouting, withReviewSession } from "./server-routing.js";
import { unconfigured } from "./config.js";

const cleanup: Array<() => Promise<void>> = [];
afterEach(async () => { for (const close of cleanup.splice(0).reverse()) await close(); });
it("routes simultaneous repositories, all authored state and failures to their own server", async () => {
  const dir = mkdtempSync(join(tmpdir(), "gander-routing-"));
  cleanup.push(async () => rmSync(dir, { recursive: true, force: true }));
  const fixture = await makeFixtureRepo(); cleanup.push(async () => rmSync(fixture.dir, { recursive: true, force: true }));
  const servers = [];
  for (const id of ["personal", "team"]) {
    const storage = openStorage(join(dir, `${id}.db`));
    const server = buildServer({ storage, token: id, version: SERVICE_VERSION });
    const url = await server.listen({ host: "127.0.0.1", port: 0 });
    cleanup.push(async () => { await server.close(); storage.close(); });
    servers.push({ server, storage, connection: { id, name: id, url, token: id } });
  }
  const [one, two] = servers;
  const cfg = { ...unconfigured(), servers: servers.map((entry) => entry.connection), repos: servers.map((entry) => ({ repoId: `${entry.connection.id}/atlas`, url: fixture.dir, localPath: fixture.dir, serverId: entry.connection.id })) };
  const pr: PrSummary = { githubId: "PR_fixture", number: 1, title: "Example", body: "", draft: false, baseRef: "main", baseSha: await fixture.git(["rev-parse", "main"]), headRef: "feature", headSha: await fixture.git(["rev-parse", "refs/pull/1/head"]), stack: null };
  const route = createServerRouting(cfg, { git: createGitEngine(join(dir, "clones")), listPrs: async () => [pr], enqueueFilesViewed: () => {}, repoUrl: () => fixture.dir, machine: "test" });
  await Promise.all(cfg.repos.map((repo) => route(repo.repoId).reviewer.openPr(repo.repoId, 1)));
  await Promise.all(cfg.repos.map((repo) => route(repo.repoId).reviewer.setCheckedMany(repo.repoId, 1, ["a.rb", "b.rb"], true)));
  const noted = await route("team/atlas").reviewer.addNote("team/atlas", 1, { path: "a.rb", line: null, text: "Team note" });
  const noteId = noted.notes[0]!.id;
  await route("team/atlas").reviewer.updateNote("team/atlas", 1, noteId, { text: "Revised" });
  expect(two!.storage.listNotes("team/atlas", 1)[0]!.text).toBe("Revised");
  expect(one!.storage.listNotes("team/atlas", 1)).toEqual([]);
  expect(one!.storage.getReview("personal/atlas", 1).files).toHaveLength(2);
  expect(two!.storage.getReview("personal/atlas", 1).files).toHaveLength(0);
  expect(await route("team/atlas").reviewer.reviewedSnapshot("team/atlas", 1, "a.rb")).toContain("class A");
  expect((await route("personal/atlas").reviewer.listPrsWithProgress("personal/atlas"))[0]!.reviewProgress).toEqual({ done: 2, total: 2 });
  await route("team/atlas").reviewer.deleteNote("team/atlas", 1, noteId);
  expect(two!.storage.listNotes("team/atlas", 1)).toEqual([]);
  const oldSession = route("personal/atlas").sessionId;
  let release!: (value: string) => void;
  const delayed = new Promise<string>((resolve) => { release = resolve; });
  const pending = withReviewSession(route, "personal/atlas", async () => delayed);
  cfg.repos[0]!.serverId = "team";
  const newSession = route("personal/atlas").sessionId;
  expect(newSession).not.toBe(oldSession);
  release("old server reply");
  await expect(pending).rejects.toThrow(/server changed while/);
  let staleMutationRan = false;
  await expect(withReviewSession(route, "personal/atlas", async () => { staleMutationRan = true; }, oldSession)).rejects.toThrow(/server changed/);
  expect(staleMutationRan).toBe(false);
  cfg.repos[0]!.serverId = "personal";
  await route("personal/atlas").reviewer.openPr("personal/atlas", 1);
  await two!.server.close();
  expect((await route("team/atlas").reviewer.refreshPr("team/atlas", 1)).files).toHaveLength(2);
  await expect(route("team/atlas").reviewer.setChecked("team/atlas", 1, "a.rb", false)).rejects.toThrow(/cached service data/);
  await route("personal/atlas").reviewer.setChecked("personal/atlas", 1, "a.rb", false);
  expect(one!.storage.getReview("personal/atlas", 1).files[0]!.checked).toBe(false);
  expect(one!.storage.getReview("team/atlas", 1).files).toEqual([]);
  cfg.servers[0]!.token = "wrong";
  await expect(route("personal/atlas").reviewer.setChecked("personal/atlas", 1, "b.rb", false)).rejects.toThrow(/must be opened first/);
  await expect(route("personal/atlas").reviewer.openPr("personal/atlas", 1)).rejects.toThrow(/rejected.*token/);
});
